/** Все эмодзи одним списком — для поиска. */
export const ALL_EMOJI: [string, string][] = EMOJI_GROUPS.flatMap(g => g.items);

/** Поиск по словам без учёта регистра и «ё»; пустой запрос — пусто (показываем группы). */
export function searchEmoji(query: string): string[] {
  const q = query.trim().toLowerCase().replace(/ё/g, "е");
  if (!q) return [];
  // Сначала точное слово, потом начало слова, потом вхождение — «баг» даёт 🐞 раньше случайных совпадений.
  const rank = (w: string): number => {
    const words = w.replace(/ё/g, "е").split(" ");
    if (words.includes(q)) return 0;
    if (words.some(x => x.startsWith(q))) return 1;
    return w.includes(q) ? 2 : 3;
  };
  return ALL_EMOJI.map(([e, w]) => [e, rank(w)] as const).filter(([, r]) => r < 3)
    .sort((a, b) => a[1] - b[1]).map(([e]) => e);
}
