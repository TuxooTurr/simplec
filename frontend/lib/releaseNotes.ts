const SEEN_KEY = "st_whatsnew_seen";

/** Показывали ли пользователю этот релиз. */
export function isReleaseSeen(id: string): boolean {
  try {
    return localStorage.getItem(SEEN_KEY) === id;
  } catch {
    // Приватный режим или запрет хранилища — не повод ломать вход в приложение.
    return true;
  }
}

export function markReleaseSeen(id: string): void {
  try {
    localStorage.setItem(SEEN_KEY, id);
  } catch { /* хранилище недоступно — просто покажем окно в следующий раз */ }
}
