/**
 * Заметки о релизах — то, что показывается пользователю в окне «Что нового».
 *
 * Новый релиз добавляется в начало RELEASES. Пока `id` не менялся, окно само
 * не открывается: пользователь уже видел этот релиз. Смена id = показать всем
 * ещё раз, поэтому id обязан меняться с каждым новым выпуском.
 */

export type ChangeKind = "new" | "improved" | "fixed";

export const KIND_LABEL: Record<ChangeKind, string> = {
  new:      "Новое",
  improved: "Улучшено",
  fixed:    "Исправлено",
};

export interface ReleaseEntry {
  kind:    ChangeKind;
  title:   string;
  text?:   string;
  /** Подробности списком — то, что важно знать до первого использования. */
  points?: string[];
  /** Наглядное «было → стало»: понятнее любого описания. */
  before?: string;
  after?:  string;
  /** Готовый пример — показывается моноширинным блоком. */
  sample?: string;
}

export interface ReleaseSection {
  area:     string;
  subtitle: string;
  entries:  ReleaseEntry[];
}

export interface Release {
  id:       string;   // сменить = показать окно заново всем
  date:     string;
  title:    string;
  summary:  string;
  sections: ReleaseSection[];
}

